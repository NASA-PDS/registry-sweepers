#!/usr/bin/env python3
"""Generate one Airflow DAG file per node from terraform output.

Usage:
  1. Fill in generate_dags.env with venue-specific constants.
  2. Run: python generate_dags.py
"""

import argparse
import json
import subprocess
import sys
from pathlib import Path

try:
    import boto3
    from botocore.exceptions import BotoCoreError, ClientError
except ImportError:
    boto3 = None

ENV_FILE = Path(__file__).parent / "generate_dags.env"
TERRAFORM_DIR = Path(__file__).parent


def load_env_file(path: Path) -> dict:
    env = {}
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            key, _, value = line.partition("=")
            env[key.strip()] = value.strip()
    return env


def _parse_json_output(cmd: str, output_name: str, stdout: str, stderr: str) -> dict:
    """Parse JSON from command output, tolerating terragrunt log lines on stdout."""
    stdout = stdout.strip()
    if not stdout:
        raise ValueError(
            f"`{cmd} output -json {output_name}` produced no stdout.\n"
            f"stderr: {stderr.strip()}"
        )
    try:
        return json.loads(stdout)
    except json.JSONDecodeError:
        # Terragrunt may prefix log lines to stdout; decode the JSON suffix.
        decoder = json.JSONDecoder()
        for start, char in enumerate(stdout):
            if char not in "{[":
                continue
            try:
                value, end = decoder.raw_decode(stdout[start:])
            except json.JSONDecodeError:
                continue
            if not stdout[start + end:].strip():
                return value
        raise ValueError(
            f"Could not parse JSON from `{cmd} output -json {output_name}`.\n"
            f"stdout: {stdout!r}\nstderr: {stderr.strip()!r}"
        )


def get_terraform_output(cmd: str = "terraform") -> tuple[dict, dict]:
    """Returns (task_arns, log_group_names) from terraform/terragrunt outputs."""
    task_arns_result = subprocess.run(
        [cmd, "output", "-json", "sweepers_task_definition_arns"],
        capture_output=True,
        text=True,
        check=True,
    )
    log_groups_result = subprocess.run(
        [cmd, "output", "-json", "sweepers_log_group_names"],
        capture_output=True,
        text=True,
        check=True,
    )
    task_arns = _parse_json_output(
        cmd, "sweepers_task_definition_arns",
        task_arns_result.stdout, task_arns_result.stderr,
    )
    log_group_names = _parse_json_output(
        cmd, "sweepers_log_group_names",
        log_groups_result.stdout, log_groups_result.stderr,
    )
    return task_arns, log_group_names


def generate_dag(node_name: str, task_arn: str, log_group: str, env: dict) -> str:
    node_upper = node_name.upper()
    node_lower = node_name.lower()
    cluster = env["ECS_CLUSTER_NAME"]
    subnets = json.loads(env["ECS_SUBNETS"])
    security_groups = json.loads(env["ECS_SECURITY_GROUPS"])

    return f'''"""PDS {node_upper} Registry Sweeper DAG.

This DAG runs the PDS {node_upper} Registry Sweeper on a scheduled basis.
It executes an ECS task on Fargate to perform registry sweeping operations.

This DAG is compatible with Airflow 3.0+
Auto-generated by generate_dags.py — do not edit manually.
"""

from datetime import datetime, timedelta
from airflow import DAG
from airflow.operators.bash import BashOperator
from airflow.providers.amazon.aws.operators.ecs import EcsRunTaskOperator
from airflow.utils.trigger_rule import TriggerRule

NODE_NAME = "{node_upper}"
DAG_ID = "PDS_{node_upper}-registry-sweeper"
ECS_TASK_DEFINITION_ARN = "{task_arn}"
ECS_CLUSTER_NAME = "{cluster}"
ECS_LAUNCH_TYPE = "FARGATE"
ECS_SUBNETS = {json.dumps(subnets)}
ECS_SECURITY_GROUPS = {json.dumps(security_groups)}

default_args = {{
    "owner": "airflow",
    "depends_on_past": False,
    "retries": 0,
    "retry_delay": timedelta(minutes=5),
}}

dag = DAG(
    dag_id=DAG_ID,
    description="Registry sweeper for PDS {node_upper}",
    schedule=timedelta(hours=1),
    start_date=datetime(2023, 1, 13),
    catchup=False,
    max_active_runs=1,
    default_args=default_args,
    tags=["pds", "registry", "sweeper", "ecs"],
)

print_start_time = BashOperator(
    task_id="Print_Start_Time",
    dag=dag,
    bash_command='echo "Registry {node_upper} Sweeper workflow started at $(date)"',
)

registry_sweeper = EcsRunTaskOperator(
    task_id="Run_Registry_Sweeper",
    dag=dag,
    cluster=ECS_CLUSTER_NAME,
    task_definition=ECS_TASK_DEFINITION_ARN,
    launch_type=ECS_LAUNCH_TYPE,
    network_configuration={{
        "awsvpcConfiguration": {{
            "securityGroups": ECS_SECURITY_GROUPS,
            "subnets": ECS_SUBNETS,
            "assignPublicIp": "DISABLED",
        }},
    }},
    overrides={{}},
    awslogs_group="{log_group}",
    awslogs_stream_prefix="ecs/pds-registry-sweepers-{node_lower}-container",
)

print_end_time = BashOperator(
    task_id="Print_End_Time",
    dag=dag,
    bash_command='echo "Registry {node_upper} Sweeper workflow completed at $(date)"',
    trigger_rule=TriggerRule.ALL_SUCCESS,
)

print_start_time >> registry_sweeper >> print_end_time
'''


def push_to_s3(bucket: str, file_path: Path, root_prefix: str = "") -> None:
    if boto3 is None:
        print("Error: boto3 is required for S3 upload. Install it with: pip install boto3", file=sys.stderr)
        sys.exit(1)
    # Node prefix is the part of the filename before the first '-', e.g. PDS_EN from PDS_EN-sweeper.py
    node_prefix = file_path.stem.split("-")[0]
    parts = [p for p in [root_prefix, node_prefix, file_path.name] if p]
    key = "/".join(parts)
    try:
        s3 = boto3.client("s3")
        s3.upload_file(str(file_path), bucket, key)
        print(f"Uploaded to s3://{bucket}/{key}")
    except (BotoCoreError, ClientError) as e:
        print(f"Error uploading {file_path.name} to S3: {e}", file=sys.stderr)
        raise


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument(
        "--terragrunt",
        action="store_true",
        default=False,
        help="Use terragrunt instead of terraform to fetch outputs.",
    )
    args = parser.parse_args()

    if not ENV_FILE.exists():
        print(f"Error: {ENV_FILE} not found. Copy generate_dags.env.example and fill in your values.", file=sys.stderr)
        sys.exit(1)

    env = load_env_file(ENV_FILE)

    required = {"ECS_CLUSTER_NAME", "ECS_SUBNETS", "ECS_SECURITY_GROUPS"}
    missing = required - env.keys()
    if missing:
        print(f"Error: missing keys in {ENV_FILE}: {', '.join(sorted(missing))}", file=sys.stderr)
        sys.exit(1)

    # --terragrunt flag takes precedence; fall back to TERRAFORM_CMD env var, then default to "terraform".
    if args.terragrunt:
        tf_cmd = "terragrunt"
    else:
        tf_cmd = env.get("TERRAFORM_CMD", "terraform").strip() or "terraform"

    try:
        task_arns, log_group_names = get_terraform_output(tf_cmd)
    except subprocess.CalledProcessError as e:
        print(f"Error running {tf_cmd} output: {e.stderr}", file=sys.stderr)
        sys.exit(1)

    output_dir = Path(env.get("DAGS_OUTPUT_DIR", "."))
    output_dir.mkdir(parents=True, exist_ok=True)

    s3_bucket = env.get("DAGS_S3_BUCKET", "").strip()
    root_prefix = env.get("DAGS_S3_ROOT_PREFIX", "").strip().strip("/")

    for node_name, task_arn in task_arns.items():
        log_group = log_group_names[node_name]
        content = generate_dag(node_name, task_arn, log_group, env)
        out_path = output_dir / f"PDS_{node_name.upper()}-sweeper.py"
        out_path.write_text(content)
        print(f"Generated {out_path}")
        if s3_bucket:
            try:
                push_to_s3(s3_bucket, out_path, root_prefix=root_prefix)
            except (BotoCoreError, ClientError):
                print(f"Error uploading {out_path}, keep uploading remaining DAGs, as needed", file=sys.stderr)



if __name__ == "__main__":
    main()
